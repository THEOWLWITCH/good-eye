"""Merge tools/i18n_en.txt (if given) into tools/i18n_strings.json and write js/core/i18n-en.js."""
import json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
sp = ROOT / 'tools' / 'i18n_strings.json'
d = json.loads(sp.read_text(encoding='utf-8'))
if len(sys.argv) > 1:
    keys = list(d.keys())
    lines = (ROOT / sys.argv[1]).read_text(encoding='utf-8').splitlines()
    for ln in lines:
        if not ln.strip():
            continue
        n, _, en = ln.partition('|')
        i = int(n) - 1
        if '\n' in keys[i]:
            en = en.replace('\n', '\n')
        d[keys[i]] = en
    assert len([l for l in lines if l.strip()]) == len(keys), (len(lines), len(keys))
sp.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding='utf-8')
# keep the Hebrew key's leading/trailing spaces (fragments are concatenated in code)
for k, v in list(d.items()):
    if not v:
        continue
    lead = k[:len(k) - len(k.lstrip(' '))]
    trail = k[len(k.rstrip(' ')):]
    d[k] = lead + v.strip(' ') + trail
missing = [k for k, v in d.items() if not v]
out = ROOT / 'js' / 'core' / 'i18n-en.js'
out.write_text('/* Generated by tools/i18n_build.py — Hebrew → English UI strings. Edit tools/i18n_strings.json. */\n'
               '(function (root) { (root.DA = root.DA || {}).i18nEN = ' + json.dumps({k: v for k, v in d.items() if v}, ensure_ascii=False, indent=0) +
               '; })(typeof window !== "undefined" ? window : globalThis);\n', encoding='utf-8')
print(f'{len(d)} strings, {len(missing)} missing:', missing[:20])
